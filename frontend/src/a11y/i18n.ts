export const A11Y_DICTS: Record<A11yLang, Dict> = { uz, ru, en };

export function pageLang(): A11yLang {
  const l = (typeof document !== "undefined" ? document.documentElement.lang : "uz").slice(0, 2);
  return l === "ru" || l === "en" ? l : "uz";
}

/** <html lang> o'zgarishini kuzatadi (sayt, kabinet va admin panel tilni o'zi qo'yadi) */
export function usePageLang(): A11yLang {
  return useSyncExternalStore(
    (f) => {
      const mo = new MutationObserver(f);
      mo.observe(document.documentElement, { attributes: true, attributeFilter: ["lang"] });
      return () => mo.disconnect();
    },
    pageLang,
    () => "uz" as A11yLang,
  );
}

export function useA11yT(): Dict {
  return A11Y_DICTS[usePageLang()];
}
