export const LANG_NATIVE: Record<Lang, string> = { uz: "O‘zbekcha", ru: "Русский", en: "English" };

const LOCALES: Record<Lang, string> = { uz: "uz-UZ", ru: "ru-RU", en: "en-GB" };
const MONTHS_UZ = ["yanvar", "fevral", "mart", "aprel", "may", "iyun", "iyul", "avgust", "sentabr", "oktabr", "noyabr", "dekabr"];

export function fmtDate(iso: string | null | undefined, lang: Lang, short = false): string {
  if (!iso) return "";
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  if (lang === "uz") return short ? `${d.getDate()} ${MONTHS_UZ[d.getMonth()].slice(0, 3)} ${d.getFullYear()}` : `${d.getDate()}-${MONTHS_UZ[d.getMonth()]}, ${d.getFullYear()}`;
  return d.toLocaleDateString(LOCALES[lang], { day: "numeric", month: short ? "short" : "long", year: "numeric" });
}

export function fmtDateTime(iso: string | null | undefined, lang: Lang): string {
  if (!iso) return "";
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  const p = (n: number) => String(n).padStart(2, "0");
  return `${fmtDate(iso, lang, true)}, ${p(d.getHours())}:${p(d.getMinutes())}`;
}
